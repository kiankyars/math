// Columns over F = D \ D0 (D, D0 down-closed, D0 subset D, 0 in D0), monotone heights on F. Check t-fiber intervals.
#include <bits/stdc++.h>
using namespace std;
typedef vector<int> V;
int main(int argc,char**argv){
  unsigned seed=atoi(argv[1]); int trials=atoi(argv[2]); int dmax=atoi(argv[3]); int side=atoi(argv[4]); int maxJ=atoi(argv[5]); int maxelts=atoi(argv[6]); int monotone=atoi(argv[7]);
  setvbuf(stdout,NULL,_IONBF,0); mt19937 rng(seed); long tested=0,bad=0;
  auto box=[&](set<V>&S,const V&gen,int d){ V x(d,0); while(true){ S.insert(x); int i=0; while(i<d){ if(x[i]<gen[i]){x[i]++;break;} x[i]=0;i++;} if(i==d) break; } };
  for(int t=0;t<trials;t++){
    int d=1+rng()%dmax; set<V> Ds,D0; int ng=1+rng()%4;
    vector<V> gens; for(int g=0;g<ng;g++){ V gen(d); for(int i=0;i<d;i++) gen[i]=rng()%(side+1); gens.push_back(gen); box(Ds,gen,d); }
    // D0: down-set generated by random elements of Ds (scaled down)
    int n0=rng()%3; D0.insert(V(d,0)); for(int g=0;g<n0;g++){ auto it=Ds.begin(); advance(it,rng()%Ds.size()); box(D0,*it,d); }
    vector<V> F; for(auto&x:Ds) if(!D0.count(x)) F.push_back(x);
    if(F.empty()) continue;
    sort(F.begin(),F.end(),[](const V&a,const V&b){int sa=0,sb=0; for(int x:a)sa+=x; for(int x:b)sb+=x; if(sa!=sb) return sa<sb; return a<b;});
    vector<int> J(F.size());
    for(size_t c=0;c<F.size();c++){ int ub=maxJ; if(monotone) for(size_t c2=0;c2<c;c2++){ bool le=true; for(int i=0;i<d;i++) if(F[c2][i]>F[c][i]) le=false; if(le) ub=min(ub,J[c2]); } J[c]=rng()%(ub+1); }
    int ne=0; for(int j:J) ne+=j+1; if(ne>maxelts) continue; tested++;
    int maxh=0; for(int j:J) maxh+=(j+1)*j/2;
    map<V,vector<char>> Dm; Dm[V(d,0)]=vector<char>(maxh+1,0); Dm[V(d,0)][0]=1;
    for(size_t c=0;c<F.size();c++){ int Jr=J[c]; map<V,vector<char>> N2;
      for(auto&kv:Dm){ V y=kv.first; for(int k=0;k<=Jr+1;k++){ int L=k*(k-1)/2,H=k*Jr-k*(k-1)/2; auto&tg=N2[y]; if(tg.empty()) tg.assign(maxh+1,0);
          for(int h=0;h<=maxh;h++) if(kv.second[h]) for(int v=L;v<=H&&h+v<=maxh;v++) tg[h+v]=1;
          for(int i=0;i<d;i++) y[i]+=F[c][i]; } }
      Dm.swap(N2); }
    for(auto&kv:Dm){ int prev=-1; bool ok=true; for(int h=0;h<=maxh;h++) if(kv.second[h]){ if(prev>=0&&h-prev>1) ok=false; prev=h; }
      if(!ok){ bad++; if(bad<=3){ printf("FAIL d=%d F:",d); for(size_t c=0;c<F.size();c++){printf(" (");for(int q:F[c])printf("%d,",q);printf(")J%d",J[c]);} printf(" u=("); for(int q:kv.first)printf("%d,",q); printf(")\n"); } break; } }
  }
  printf("monotone=%d tested=%ld bad=%ld\n",monotone,tested,bad);
}
